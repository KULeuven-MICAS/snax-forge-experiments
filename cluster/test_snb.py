def test_run_do_in_vsim_command():
    # the run's own do in place of VSIM_FLAGS' `log -r /*; run -a`: no waveform log
    script = 'vsim $(realpath $1) -do "log -r /*; run -a" $3 +x ++$2\n'
    out = pw.vsim_command(script, Path("/w/gls/run.do"), Path("/w/sw/plain.elf"))
    assert "log -r" not in out and "-do /w/gls/run.do" in out and " -batch " in out
    assert "log" not in snb.RUN_DO and "run -all" in snb.RUN_DO and "quit -f" in snb.RUN_DO


def test_part1_current_keys():
    # part 1's check.json carries the keys power.part1_current reads, so a current part 1 is skipped
    pre = {"repos": {"snax_cluster": "c" * 40, "snax_cluster_branch": "main", "snax_cluster_on_main": True},
           "synz": snb.ROOT / "syn/runs/snb/nangate45/snitch1_cg.zip", "netlist_sha": "n" * 64,
           "netlist_commit": "c" * 40, "prov": {"elf_sha256": "e" * 64}, "quiet_sha": "q" * 64, "cells": "cells.v",
           "images": {"snax_cluster": "img", "snax_cluster_id": "id"}}
    res = snb.part1_head("snitch1_cg_dot_int64", pre, [])
    assert res["point"] == "snitch1_cg_dot_int64" and "run" not in res     # part 1 puts the run's checks under run
    res["status"] = "PASS"
    assert pw.part1_current(res, "n" * 64, "q" * 64, "c" * 40)[0]
    assert not pw.part1_current(res, "m" * 64, "q" * 64, "c" * 40)[0]


def test_site():
    s = snb.SITE
    assert s.strip == "tb_bin/i_dut/i_snax_snitch_cluster" and s.netlist == "out/snax_snitch_cluster_wrapper_mapped.v"
    assert s.run_zips == snb.ROOT / "sim/runs/snb/nangate45" and s.tmp == snb.ROOT / "tmp/snb"
    assert s.power_csv == snb.ROOT / "results/snb/nangate45/power_pt.csv"
    assert s.power_reports == snb.ROOT / "results/snb/nangate45/power_reports"
    # part 2 strips the SAIF at power.py's STRIP_LEVELS, the forge testbench's depth: this one has the same
    assert len(s.strip.split("/")) == pw.STRIP_LEVELS
    f = pw.forge_site()
    assert (f.strip, f.netlist, f.power_csv) == (pw.STRIP, cl.NETLIST, pw.POWER_CSV)


