def exits(fn, *a, has: str = "") -> str:
    try:
        fn(*a)
    except SystemExit as e:
        assert has in str(e), (has, str(e))
        return str(e)
    raise AssertionError(f"{fn.__name__} did not exit")


# ---------------------------------------------------------------- points
def test_points_configs():
    cs = {c["config"]: c for c in PTS["configs"]}
    assert list(cs) == ["snitch1_cg", "snitch5_cg", "snitch9_cg"]
    for n, (cores, workers) in zip(cs, ((1, 1), (5, 4), (9, 8))):
        c = cs[n]
        assert c["cfg"] == f"cfg/snax_snitch_cluster_{cores}.hjson"          # the literal path the apps Makefile wants
        assert (c["cores"], c["workers"]) == (cores, workers)
        assert c["srams"] == {"sram_d128_w256_m8": 2, "sram_d128_w39": 2, "sram_d512_w64_m8": 32}
        assert c["syn"] == {"clk_gate": True} and len(c["netlist_sha256"]) == 64
        int(c["netlist_sha256"], 16)


def test_n_op_table():
    # the kernels' maths at their default sizes; a multiply-accumulate counts two
    want = {"vecadd": 2048, "vecmul": 2048, "relu": 2048, "axpy": 4096, "vsum": 2047, "dot": 4096,
            "rowsum": 16 * 127, "matvec": 2 * 16 * 512, "matadd": 32 * 64, "mvt": 4 * 64 * 64,
            "atax": 4 * 64 * 64, "bicg": 4 * 64 * 64, "gesummv": 4 * 64 * 64 + 3 * 64,
            "dma_transpose": 64 * 64}  # the elements the copy moves (X95), not E11's
    got = {k: snb.n_op(v["n_op"], v["sizes"]) for k, v in PTS["kernels"].items()}
    assert got == want, got


def test_n_op_grammar():
    assert snb.n_op("(M+1)*N//2 - 3", {"M": 3, "N": 10}) == 17
    for bad in ("N**2", "X", "N/2", "abs(N)", "1.5*N"):
        try:
            snb.n_op(bad, {"N": 8})
        except ValueError as e:
            assert "+ - * //" in str(e)
        else:
            raise AssertionError(bad)


def test_run_names():
    r = snb.run_of(PTS, "snitch9_cg_matvec_int32")
    assert (r["config"]["config"], r["kernel"], r["type"], r["sizes"], r["n_op"], r["seed"]) == \
        ("snitch9_cg", "matvec", "int32", {"M": 16, "N": 512}, 16384, 42)
    assert snb.make_args(r) == "CFG_OVERRIDE=cfg/snax_snitch_cluster_9.hjson TYPE=int32 SEED=42 M=16 N=512"
    assert snb.data_line(r) == "// matvec's data, generated by datagen.py: M=16 N=512, TYPE=int32, seed 42"
    assert snb.data_line(snb.run_of(PTS, "snitch5_cg_mvt_i8")) == \
        "// mvt's data, generated by datagen.py: M=64 N=64, TYPE=i8, seed 42"
    assert snb.make_args(snb.run_of(PTS, "snitch9_cg_gesummv_int64")) == \
        "CFG_OVERRIDE=cfg/snax_snitch_cluster_9.hjson TYPE=int64 SEED=42 N=64"
    for bad in ("snitch1_cg_dot", "snitch1_cg_dot_int65", "snitch2_cg_dot_int64", "snitch1_cg_gemm_int64", "dot_int64"):
        exits(snb.run_of, PTS, bad, has="is not <config>_<kernel>_<type>")
    exits(snb.config_of, PTS, "snitch3_cg", has="no config")


# ---------------------------------------------------------------- the program's output
OUT = """# [tc_sram_impl] something
snitch-forge dot int64 N=2048 workers 4
snitch-forge cycles dma_in: 1201
snitch-forge cycles run: 19050
snitch-forge cycles dma_out: 64
snitch-forge core 0 compute: 18960
snitch-forge core 1 compute: 18980
snitch-forge core 2 compute: 18981
snitch-forge core 3 compute: 18983
snitch-forge errors: 0
# [SUCCESS] Program finished successfully
"""


def run5():
    return snb.run_of(PTS, "snitch5_cg_dot_int64")


def test_parse_output():
    o = snb.parse_output(OUT)
    assert o["header"] == {"kernel": "dot", "type": "int64", "sizes": {"N": 2048}, "workers": 4}
    assert o["cycles"] == {"dma_in": 1201, "run": 19050, "dma_out": 64}
    assert o["compute"] == {0: 18960, 1: 18980, 2: 18981, 3: 18983}
    assert (o["errors"], o["first_error"], o["success"], o["failure"]) == (0, None, True, False)
    two = snb.parse_output("snitch-forge rowsum int32 M=16 N=128 workers 8\n")
    assert two["header"]["sizes"] == {"M": 16, "N": 128}


def test_program_checks_pass():
    c = snb.program_checks(snb.parse_output(OUT), run5())
    assert snb.failed(c) == [], c


def test_program_checks_fail():
    cases = {"errors": OUT.replace("errors: 0", "errors: 3\nsnitch-forge first error at 17"),
             "header": OUT.replace("workers 4", "workers 8"),
             "success": OUT.replace("[SUCCESS] Program finished successfully", "[FAILURE] Finished with exit code 1"),
             "compute": OUT.replace("snitch-forge core 3 compute: 18983\n", ""),
             "cycles": OUT.replace("snitch-forge cycles dma_out: 64\n", "")}
    for want, text in cases.items():
        assert snb.failed(snb.program_checks(snb.parse_output(text), run5())) == [want], want
    assert snb.parse_output(cases["errors"])["first_error"] == 17
    # the right program but another size is a header failure too
    assert snb.failed(snb.program_checks(snb.parse_output(OUT.replace("N=2048", "N=1024")), run5())) == ["header"]


def test_merge_runs():
    with tempfile.TemporaryDirectory() as d:
        f = Path(d) / "runs.csv"
        base = {"config": "snitch5_cg", "kernel": "dot", "type": "int64", "sizes": "N=2048", "workers": 4, "n_op": 4096}
        snb.merge_runs(f, {"run": "snitch5_cg_vecadd_int64", **base, "kernel": "vecadd", "rtl_run": 13860})
        snb.merge_runs(f, {"run": "snitch5_cg_dot_int64", **base, "rtl_run": 19050, "elf_sha256": "a"})
        snb.merge_runs(f, {"run": "snitch5_cg_dot_int64", "gls_run": 19050, "gls_status": "PASS", "netlist_sha256": "n"})
        rows = list(csv.DictReader(f.open()))
        assert [r["run"] for r in rows] == ["snitch5_cg_dot_int64", "snitch5_cg_vecadd_int64"]
        assert (rows[0]["rtl_run"], rows[0]["gls_run"], rows[0]["gls_status"]) == ("19050", "19050", "PASS")
        assert list(rows[0]) == snb.RUN_COLUMNS
        # a new ELF: the gate-level columns are of the old one, so they go
        snb.merge_runs(f, {"run": "snitch5_cg_dot_int64", "rtl_run": 19051, "elf_sha256": "b"},
                       clear=snb.GLS_COLUMNS + ["gls_date"])
        r = list(csv.DictReader(f.open()))[0]
        assert (r["rtl_run"], r["elf_sha256"], r["gls_run"], r["gls_status"], r["netlist_sha256"], r["kernel"]) == \
            ("19051", "b", "", "", "", "dot")


