def test_swap_check_top():
    netlist = Path("/w/netlist/snax_snitch_cluster_wrapper_mapped.v")
    vlog = f"-- Compiling ... {netlist}\n"
    ok = cl.swap_check(VOPT, vlog, "", netlist, {"NAND2_X1"}, top=snb.TOP)
    assert ok["status"] == "PASS" and ok["wrapper_from"] == ["work-vsim/gls"], ok
    assert (ok["cells_loaded"], ok["netlist_modules_loaded"]) == (1, 2)
    assert cl.swap_check(VOPT, vlog, "", netlist, {"NAND2_X1"})["status"] == "FAIL"     # forge's wrapper is not here


def test_syn_source():
    synpy.use_source("snb")
    assert synpy.top_of("snitch1_cg") == "snax_snitch_cluster_wrapper" == snb.TOP
    assert synpy.run_zip("nangate45", "snitch1_cg", synpy.DEFAULT_CLOCK) == snb.ROOT / "syn/runs/snb/nangate45/snitch1_cg.zip"
    assert synpy.RESULTS == snb.ROOT / "results/snb"
    assert synpy.columns()[-len(synpy.CLUSTER_COLUMNS):] == synpy.CLUSTER_COLUMNS
    assert "reports/cluster_check.rpt" in synpy.keep_run() and "tree.txt" in synpy.kept_reports()
    exits(synpy.cmd_run, None, has="pixi run snb syn")
    synpy.use_source("cluster")
    assert synpy.top_of("x") == "snax_forge_cluster_wrapper"


