"""CSYN1 Part B: a cluster's memories as RAM1 macros, through one generated tc_sram_impl.sv (X66).

    pixi run python cluster/mem.py MEMORIES_JSON OUT_DIR             # macros, models, tc_sram_impl.sv
    pixi run python cluster/mem.py MEMORIES_JSON OUT_DIR --text-only # tc_sram_impl.sv alone (no lc_shell)

MEMORIES_JSON is snax_cluster's memory list, `util/clustergen.py -c <cluster file> -o <dir> --memories`
(clustergen's `memory_cfg`, `<dir>/memories.json`): one entry per memory size, with its words, width,
byte width, ports, latency, byte enable and the memories it stands for. Each entry becomes one RAM1 macro
(`ram/ram.py` `make_macro`, X49): `sram_d<words>_w<width>`, with `_m8` where the list sets byte enable.
OUT_DIR gets:

    tc_sram_impl.sv   snax_cluster's tc_sram_impl (parameters and ports of tech_cells_generic's), one
                      branch per macro, read through snax_cluster's SRAM_IMPL
    models/<name>.v   the macros' behavioural models, out of ram/runs/lib/<name>.zip
    sram_models.f     -sv, then the models' absolute paths, read through snax_cluster's SRAM_MODELS (vsim
                      only); the models are SystemVerilog in .v files, which vlog reads as Verilog-2001
                      without -sv (PITFALLS Q12); snax_cluster's list of SRAM_MODELS files skips option lines
    mem.json          the macros and the list entries they come from

None of it is committed (X49); a run zips OUT_DIR's files with its outputs (X51).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "arc"))
sys.path.insert(0, str(ROOT / "ram"))

MASK = 8   # the macros' byte enable: one bit per 8 bits (X49)


def load(path: Path) -> list[dict]:
    return json.loads(Path(path).read_text())


def macros(memories: list[dict]) -> list[dict]:
    """One macro per entry of the list: name, depth, width, mask (8 or None) and the entry's memories."""
    out = []
    for m in memories:
        what = ", ".join(m.get("description") or []) or f"{m['words']} x {m['width']}"
        if m.get("ports", 1) != 1 or m.get("dual_port"):
            raise ValueError(f"{what}: {m.get('ports')} ports; the macros have one")
        if m.get("latency", 1) != 1:
            raise ValueError(f"{what}: latency {m.get('latency')}; the macros read in one cycle")
        mask = MASK if m.get("byte_enable") else None
        if mask and m.get("byte_width", MASK) != MASK:
            raise ValueError(f"{what}: byte width {m['byte_width']}; the macros' byte enable is every {MASK} bits")
        if mask and m["width"] % mask:
            raise ValueError(f"{what}: width {m['width']} is not a multiple of the byte enable's {mask}")
        name = f"sram_d{m['words']}_w{m['width']}" + (f"_m{mask}" if mask else "")
        out.append({"name": name, "depth": m["words"], "width": m["width"], "mask": mask,
                    "memories": m.get("description") or []})
    names = [x["name"] for x in out]
    if len(set(names)) != len(names):
        raise ValueError(f"two entries give the same macro: {names}")
    return sorted(out, key=lambda x: (x["depth"], x["width"], x["mask"] or 0))


HEADER = """\
// tc_sram_impl for one snax_cluster configuration: every memory of the cluster as one RAM1 macro.
// Generated by snax-forge-experiments cluster/mem.py (X66) from snax_cluster's memory list; never committed.
// Parameters and ports are tech_cells_generic's tc_sram_impl; snax_cluster reads this file instead of
// tech_cells_generic's tc_sram.sv and tc_sram_impl.sv (SRAM_IMPL). One branch per macro, chosen by
// NumWords, DataWidth and (for a macro with byte enable) ByteWidth; the macro's ports are tc_sram_impl's
// port 0 (X49). impl_i is unused and impl_o is 0. NumPorts or Latency other than 1, or a size with no
// macro, is an elaboration error. In simulation each instance prints the macro it holds.
"""

MODULE_TOP = """\
module tc_sram_impl #(
  parameter int unsigned NumWords     = 32'd1024, // Number of Words in data array
  parameter int unsigned DataWidth    = 32'd128,  // Data signal width
  parameter int unsigned ByteWidth    = 32'd8,    // Width of a data byte
  parameter int unsigned NumPorts     = 32'd2,    // Number of read and write ports
  parameter int unsigned Latency      = 32'd1,    // Latency when the read data is available
  parameter              SimInit      = "none",   // Simulation initialization (unused: the models' own)
  parameter bit          PrintSimCfg  = 1'b0,     // Print configuration (unused)
  parameter              ImplKey      = "none",   // Reference to specific implementation (unused)
  parameter type         impl_in_t    = logic,    // Type for implementation inputs
  parameter type         impl_out_t   = logic,    // Type for implementation outputs
  parameter impl_out_t   ImplOutSim   = 'X,       // Implementation output in simulation (unused)
  // DEPENDENT PARAMETERS, DO NOT OVERWRITE!
  parameter int unsigned AddrWidth = (NumWords > 32'd1) ? $clog2(NumWords) : 32'd1,
  parameter int unsigned BeWidth   = (DataWidth + ByteWidth - 32'd1) / ByteWidth, // ceil_div
  parameter type         addr_t    = logic [AddrWidth-1:0],
  parameter type         data_t    = logic [DataWidth-1:0],
  parameter type         be_t      = logic [BeWidth-1:0]
) (
  input  logic                 clk_i,      // Clock
  input  logic                 rst_ni,     // Asynchronous reset active low (unused: the macros have none)
  // implementation-related IO
  input  impl_in_t             impl_i,
  output impl_out_t            impl_o,
  // input ports
  input  logic  [NumPorts-1:0] req_i,      // request
  input  logic  [NumPorts-1:0] we_i,       // write enable
  input  addr_t [NumPorts-1:0] addr_i,     // request address
  input  data_t [NumPorts-1:0] wdata_i,    // write data
  input  be_t   [NumPorts-1:0] be_i,       // write byte enable
  // output ports
  output data_t [NumPorts-1:0] rdata_o     // read data
);

  assign impl_o = '0;

  if (NumPorts != 1 || Latency != 1) begin : gen_unsupported
    $error("tc_sram_impl: NumPorts %0d and Latency %0d; the macros have one port and latency 1",
           NumPorts, Latency);
"""


def branch(m: dict) -> str:
    """The `else if` branch of one macro: its size condition, the macro on port 0, its print."""
    cond = f"NumWords == {m['depth']} && DataWidth == {m['width']}"
    if m["mask"]:
        cond += f" && ByteWidth == {m['mask']}"
    ports = [("clk_i", "clk_i"), ("req_i", "req_i[0]"), ("we_i", "we_i[0]"), ("addr_i", "addr_i[0]"),
             ("wdata_i", "wdata_i[0]")] + ([("be_i", "be_i[0]")] if m["mask"] else []) + [("rdata_o", "rdata_o[0]")]
    lines = [f"  end else if ({cond}) begin : gen_{m['name']}"]
    if m["memories"]:
        lines.append(f"    // {'; '.join(m['memories'])}")
    lines.append(f"    {m['name']} i_macro (")
    lines += [f"      .{p:<7s} ( {s:<10s} )" + ("," if i < len(ports) - 1 else "") for i, (p, s) in enumerate(ports)]
    lines += ["    );",
              "    // pragma translate_off",
              f'    initial $display("[tc_sram_impl] %m: {m["name"]}");',
              "    // pragma translate_on"]
    return "\n".join(lines) + "\n"


MODULE_END = """\
  end else begin : gen_no_macro
    $error("tc_sram_impl: no macro for NumWords %0d, DataWidth %0d, ByteWidth %0d",
           NumWords, DataWidth, ByteWidth);
  end

endmodule
"""


def impl_text(ms: list[dict]) -> str:
    return HEADER + "\n" + MODULE_TOP + "".join(branch(m) for m in ms) + MODULE_END


def models_f(ms: list[dict], out: Path) -> str:
    """sram_models.f: -sv (the models are SystemVerilog in .v files, PITFALLS Q12), then each model's absolute path."""
    return "-sv\n" + "".join(f"{(out / 'models' / (m['name'] + '.v')).resolve()}\n" for m in ms)


def make(memories_json: Path, out: Path, text_only: bool = False) -> dict:
    """Write OUT_DIR's files (module docstring); with text_only, tc_sram_impl.sv and mem.json alone."""
    ms = macros(load(memories_json))
    out.mkdir(parents=True, exist_ok=True)
    (out / "tc_sram_impl.sv").write_text(impl_text(ms))
    res = {"memories_json": str(memories_json), "macros": ms}
    if not text_only:
        import arc  # noqa: E402  arc/arc.py (X51)
        import ram  # noqa: E402  ram/ram.py: the macros (X49), lc_shell where a macro is not cached
        (out / "models").mkdir(exist_ok=True)
        bad = []
        for m in ms:
            r = ram.make_macro(m["depth"], m["width"], m["mask"])
            m["status"], m["cached"] = r["status"], r.get("cached")
            if r["status"] != "ok":
                bad.append(f"{m['name']}: {r['status']}")
                continue
            (out / "models" / f"{m['name']}.v").write_bytes(arc.read(ram.macro_zip(m["name"]), f"{m['name']}.v"))
        if bad:
            raise SystemExit("macros that failed: " + "; ".join(bad))
        (out / "sram_models.f").write_text(models_f(ms, out))
    (out / "mem.json").write_text(json.dumps(res, indent=2) + "\n")
    return res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("memories_json", type=Path)
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--text-only", action="store_true", help="tc_sram_impl.sv and mem.json only (no macros)")
    a = ap.parse_args()
    res = make(a.memories_json, a.out_dir, a.text_only)
    for m in res["macros"]:
        print(f"{m['name']:20s} {'; '.join(m['memories'])}")
    print(f"wrote {a.out_dir}/tc_sram_impl.sv" + ("" if a.text_only else ", models/, sram_models.f") + ", mem.json")


if __name__ == "__main__":
    main()
