#!/usr/bin/env python3
"""strm/gen.py - the streamer reader and the TCDM sparse interconnect, one bundle per point (STRM1).

  pixi run strm-rtl [--only POINT ...] [--set streamer|xbar|xbar_mix] [--list] [--dry-run] [--mem MB]

The grid, the snax_cluster commit and the image are in strm/grid.json. A point is
streamer/d<fifo_depth>_l<temporal_dim>_c<num_channel>, xbar/i<inputs>_b<banks> or
xbar_mix/i<inputs>_b<banks>_r<ro>_w<wo>; --only takes names or shell globs (with or
without the set, e.g. 'd8_*' or 'xbar/i16_b32'). Default: every point of the three
sets. A set's points are its axes' product, then its `extra` list (xbar: i36_b32,
the cluster's 36 inputs, which only xbar_mix reads).

xbar_mix (CSYN1 R3c) runs no sbt: a point is its base xbar point's SparseInterconnect
(rtl/xbar/i<inputs>_b<banks>.zip, made first in the same call when it is missing or
stale) inside strm/xbar_mix.py's wrapper, inputs 0..ro-1 read-only and ro..ro+wo-1
write-only. Its axes are inputs x banks, each with grid.json's mixes (rw: r0_w0,
ro: r<inputs>_w0, wo: r0_w<inputs>), then its extra points.

snax_cluster is read only. Its checkout (grid.json's path, relative to this repo)
must be at grid.json's commit; the sources are exported from that commit with
`git archive` (hw/chisel and hw/chisel_acc, the chisel-float submodule at the
commit's gitlink) into tmp/strm/src/, so sbt's target/ folders never land in
snax_cluster. The selected points' configs go to tmp/strm/<set>/<point>/, and
one sbt call in the image (grid.json's image; the home folder's ~/.sbt, ~/.ivy2,
~/.cache/coursier, ~/.cache/sbt and ~/.cache/llvm-firtool mounted under /root)
runs `compile` and then one `runMain` per point:

  streamer  snax.streamer.StreamerGen, the hjson entry point snaxgen uses: one
            reader (data_reader_params: spatial_bounds [[C]], temporal_dim [L],
            num_channel [C], fifo_depth [D], which sets both the address and the
            data buffer depth), --tcdm-size 128 --tcdm-data-width 64 --tag-name strm.
            Streamer.sv holds the CSR manager and the streamer; the bundle keeps
            the reader, strm__C0_Reader, and every module under it.
  xbar      snax.sparse_interconnect.SparseInterconnectGen with NumInp, NumOut and
            grid.json's fixed widths (memAddrWidth = log2(TCDM bytes / banks / 8)),
            sparseConfig [[NumInp, 1]]; top SparseInterconnect.

A point's zip, rtl/streamer/<point>.zip or rtl/xbar/<point>.zip (git-ignored, X51):
  <top>.sv      firtool's preamble (the macro block before the first module), then
                the top's modules, children before parents
  filelist.f    '# top: <top>', then <top>.sv (syn/scripts/dc_syn.tcl's format)
  config.json   what was generated: set, point, params, main class and arguments,
                top, snax_cluster commit, image (a point whose zip has the same
                config.json is skipped)
  point.json    provenance: the tool versions, the modules, the runMain seconds, date
  gen.log       the point's runMain output from the sbt log
An xbar_mix point's zip, rtl/xbar_mix/<point>.zip: SparseInterconnect.sv (the base
zip's bytes), xbar_mix.sv (the wrapper), filelist.f ('# top: xbar_mix', then both),
config.json (the base point's config with set, point, params and top its own, plus
base, ro, wo and xbar_mix.py's md5) and point.json (the base's provenance, both
modules' port counts, the SV's md5).
Each zip is test-read (arc.write) and tmp/strm/ is deleted at the end, also on a
failure. sbt -batch stops at the first failing command: the points after it are
reported as not run and are generated by the next call (the made ones are skipped).
Standard library and arc/arc.py only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import fnmatch
import hashlib
import io
import json
import math
import os
import re
import shlex
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "arc"))
import arc  # noqa: E402  arc/arc.py: a bundle is one zip (X51)
sys.path.insert(0, str(ROOT / "strm"))
import xbar_mix  # noqa: E402  strm/xbar_mix.py: the wrapper with read-only and write-only inputs (CSYN1 R3c)

GRID = ROOT / "strm" / "grid.json"
TMP = ROOT / "tmp" / "strm"
RTL = ROOT / "rtl"
SETS = ("streamer", "xbar", "xbar_mix")
SBT_SETS = ("streamer", "xbar")      # made by sbt; xbar_mix wraps an xbar point's SV
MIX = "xbar_mix"
MIXES = {"rw": lambda n: (0, 0), "ro": lambda n: (n, 0), "wo": lambda n: (0, n)}   # (ro, wo) for n inputs
MIX_PY = ROOT / "strm" / "xbar_mix.py"
SUBMODULE = "hw/chisel_acc/subprojects/chisel-float"
CACHES = (".sbt", ".ivy2", ".cache/coursier", ".cache/sbt", ".cache/llvm-firtool")
TAIL = 30  # lines of a failure's log printed


# ---------------------------------------------------------------- the grid
def load_grid() -> dict:
    return json.loads(GRID.read_text())


def checkout(grid: dict) -> Path:
    return (ROOT / grid["snax_cluster"]["path"]).resolve()


def all_points(grid: dict) -> list[dict]:
    """[{set, point, params}] for every point of the sets, in the axes' order (xbar_mix: each combination's mixes
    in grid.json's order), then each set's extra points."""
    out = []
    for s in SETS:
        axes = grid[s]["axes"]
        keys = list(axes)
        combos = [{}]
        for k in keys:
            combos = [{**c, k: v} for c in combos for v in axes[k]]
        if s == MIX:
            combos = [{**c, "ro": ro, "wo": wo} for c in combos for m in grid[s]["mixes"]
                      for ro, wo in [MIXES[m](c["inputs"])]]
        for c in combos + grid[s].get("extra", []):
            out.append({"set": s, "point": grid[s]["name"].format(**c), "params": c})
    return out


def base_of(grid: dict, p: dict) -> dict:
    """An xbar_mix point's base xbar point: the same inputs and banks."""
    prm = p["params"]
    c = {"inputs": prm["inputs"], "banks": prm["banks"]}
    return {"set": "xbar", "point": grid["xbar"]["name"].format(**c), "params": c}


def md5_file(path: Path) -> str:
    return hashlib.md5(path.read_bytes()).hexdigest()


def select(points: list[dict], only: list[str], sets: list[str]) -> list[dict]:
    pts = [p for p in points if not sets or p["set"] in sets]
    if only:
        pts = [p for p in pts if any(fnmatch.fnmatchcase(p["point"], pat)
                                     or fnmatch.fnmatchcase(f"{p['set']}/{p['point']}", pat) for pat in only)]
    return pts


def config(grid: dict, p: dict) -> dict:
    """What is generated for a point: main class, arguments ({sv} and {hdr} stand for the output folders); an
    xbar_mix point's is its base's with set, point, params and top its own, plus base, ro, wo and xbar_mix.py's md5."""
    s, prm = p["set"], p["params"]
    if s == MIX:
        b = base_of(grid, p)
        return {**config(grid, b), "set": s, "point": p["point"], "params": prm, "top": "xbar_mix",
                "base": f"{b['set']}/{b['point']}", "ro": prm["ro"], "wo": prm["wo"], "xbar_mix_md5": md5_file(MIX_PY)}
    if s == "streamer":
        fx = grid["streamer"]["fixed"]
        c = prm["num_channel"]
        cfg = {"data_reader_params": {"spatial_bounds": [[c]], "temporal_dim": [prm["temporal_dim"]],
                                      "num_channel": [c], "fifo_depth": [prm["fifo_depth"]]}}
        tag = fx["tag_name"]
        main = "snax.streamer.StreamerGen"
        args = ["--streamercfg", json.dumps({f"{tag}_streamer": cfg}, separators=(",", ":")),
                "--tcdm-size", str(fx["tcdm_size_kib"]), "--tcdm-data-width", str(fx["tcdm_data_width"]),
                "--tag-name", tag, "--header-dir", "{hdr}", "--hw-target-dir", "{sv}"]
        top = f"{tag}__C0_Reader"   # Streamer.scala: Reader(param, tagName + "_C" + i), tagName = tag + "_"
    else:
        fx = grid["xbar"]["fixed"]
        n_in, banks = prm["inputs"], prm["banks"]
        depth = fx["tcdm_size_kib"] * 1024 // banks // (fx["dataWidth"] // 8)
        main = "snax.sparse_interconnect.SparseInterconnectGen"
        args = ["--NumInp", str(n_in), "--NumOut", str(banks), "--memAddrWidth", str(int(math.log2(depth))),
                "--tcdmAddrWidth", str(fx["tcdmAddrWidth"]), "--dataWidth", str(fx["dataWidth"]),
                "--strbWidth", str(fx["strbWidth"]), "--priorityWidth", str(fx["priorityWidth"]),
                "--userWidth", str(fx["userWidth"]), "--sparseConfig", f"[[{n_in}, 1]]", "--hw-target-dir", "{sv}"]
        top = "SparseInterconnect"
    return {"set": s, "point": p["point"], "params": prm, "main": main, "args": args, "top": top,
            "snax_cluster_commit": grid["snax_cluster"]["commit"], "image": grid["image"]}


def config_text(cfg: dict) -> str:
    return json.dumps(cfg, indent=1) + "\n"


def zip_of(p: dict) -> Path:
    return RTL / p["set"] / f"{p['point']}.zip"


def up_to_date(p: dict, cfg: dict) -> bool:
    z = zip_of(p)
    return arc.has(z, "config.json") and arc.read_text(z, "config.json") == config_text(cfg)


# ---------------------------------------------------------------- snax_cluster, read only
def git(repo: Path, *args: str, binary: bool = False):
    done = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, check=True)
    return done.stdout if binary else done.stdout.decode().strip()


def check_checkout(grid: dict) -> tuple[Path, str]:
    """The checkout and the chisel-float commit; exits unless HEAD is grid.json's commit."""
    sc, want = checkout(grid), grid["snax_cluster"]["commit"]
    if not (sc / ".git").exists():
        sys.exit(f"no snax_cluster checkout at {sc} (grid.json snax_cluster.path)")
    head = git(sc, "rev-parse", "HEAD")
    if head != want:
        sys.exit(f"refused: {sc} is at {head}, grid.json wants {want}")
    sub = git(sc, "ls-tree", want, SUBMODULE).split()
    if len(sub) < 3 or sub[1] != "commit":
        sys.exit(f"{SUBMODULE} is not a submodule at {want}")
    try:
        git(sc / SUBMODULE, "cat-file", "-e", f"{sub[2]}^{{commit}}")
    except subprocess.CalledProcessError:
        sys.exit(f"{sc / SUBMODULE} has no commit {sub[2]} (git submodule update)")
    return sc, sub[2]


def extract(repo: Path, rev: str, paths: list[str], dest: Path) -> None:
    data = git(repo, "archive", "--format=tar", rev, *paths, binary=True)
    dest.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
        tf.extractall(dest, filter="data")


def export_sources(grid: dict, sc: Path, sub_sha: str, src: Path) -> None:
    extract(sc, grid["snax_cluster"]["commit"], ["hw/chisel", "hw/chisel_acc"], src)
    extract(sc / SUBMODULE, sub_sha, [], src / SUBMODULE)


def versions(src: Path) -> dict:
    chisel = src / "hw" / "chisel"
    sbt = re.search(r"sbt\.version\s*=\s*(\S+)", (chisel / "project" / "build.properties").read_text())
    ch = re.search(r'chiselVersion\s*=\s*"([^"]+)"', (chisel / "build.sbt").read_text())
    sc = re.search(r'scalaVersion\s*:=\s*"([^"]+)"', (chisel / "build.sbt").read_text())
    return {"sbt": sbt.group(1) if sbt else "", "chisel": ch.group(1) if ch else "",
            "scala": sc.group(1) if sc else ""}


# ---------------------------------------------------------------- the emitted SV
MODULE = re.compile(r"^module\s+(\w+)\b")
INSTANCE = re.compile(r"^\s*(\w+)\s+(?:#\(.*?\)\s*)?\w+\s*\(", re.M)


def split_modules(text: str) -> tuple[str, dict[str, str]]:
    """firtool's file: the preamble before the first module, and {module: its text}, the comment lines
    between the previous endmodule and it included."""
    lines = text.splitlines(keepends=True)
    pre, mods, gap, cur, name = [], {}, [], None, None
    for ln in lines:
        if cur is None:
            m = MODULE.match(ln)
            if m:
                name, cur = m.group(1), gap + [ln]
                gap = []
            elif mods:
                gap.append(ln)
            else:
                pre.append(ln)
            continue
        cur.append(ln)
        if ln.startswith("endmodule"):
            mods[name] = "".join(cur)
            cur = None
    if cur is not None:
        raise ValueError(f"module {name} has no endmodule")
    return "".join(pre), mods


def subtree(mods: dict[str, str], top: str) -> list[str]:
    """top and every module under it, children before parents (post-order)."""
    if top not in mods:
        raise KeyError(f"no module {top} (modules: {', '.join(mods)})")
    order, seen = [], set()

    def visit(m: str) -> None:
        seen.add(m)
        for child in INSTANCE.findall(mods[m]):
            if child in mods and child not in seen and child != m:
                visit(child)
        order.append(m)

    visit(top)
    return order


REG = re.compile(r"^\s*reg\s+(?:\[(\d+):(\d+)\]\s+)?(\w+)\s*(?:\[(\d+):(\d+)\])?\s*;", re.M)


def flop_bits(sv: str, top: str) -> int:
    """The register and memory bits the bundle's RTL declares under `top`, over the instance tree: firtool writes
    a register as `reg [h:l] x;` (1 bit without a range) and a memory as `reg [h:l] x [0:N-1];`. Its `_RANDOM*`
    temporaries live only in the simulation-only init blocks and are skipped. DC's flop count must equal it (STRM1
    R0: no register trimmed)."""
    _pre, mods = split_modules(sv)
    memo: dict[str, int] = {}

    def total(m: str) -> int:
        if m not in memo:
            n = 0
            for h, lo, name, a, b in REG.findall(mods[m]):
                if not name.startswith("_RANDOM"):
                    n += (int(h) - int(lo) + 1 if h else 1) * (abs(int(b) - int(a)) + 1 if a else 1)
            for child in INSTANCE.findall(mods[m]):
                if child in mods and child != m:
                    n += total(child)
            memo[m] = n
        return memo[m]

    return total(top)


def bundle(cfg: dict, sv_dir: Path) -> tuple[dict[str, bytes], dict]:
    """The zip's SV and file list from the emitted folder, and facts for point.json."""
    files = sorted(sv_dir.glob("*.sv"))
    if not files:
        raise FileNotFoundError(f"no .sv in {sv_dir}")
    pre, mods = "", {}
    for f in files:
        p, m = split_modules(f.read_text())
        pre = pre or p
        clash = set(m) & set(mods)
        if clash:
            raise ValueError(f"module(s) {', '.join(sorted(clash))} in more than one file")
        mods.update(m)
    top = cfg["top"]
    keep = subtree(mods, top)
    firtool = re.search(r"Generated by CIRCT (\S+)", pre)
    sv = pre + "".join(mods[m] for m in keep)
    members = {f"{top}.sv": sv.encode(), "filelist.f": f"# top: {top}\n{top}.sv\n".encode()}
    facts = {"top": top, "modules": keep, "dropped": sorted(set(mods) - set(keep)),
             "emitted": [f.name for f in files], "firtool": firtool.group(1) if firtool else ""}
    return members, facts


# ---------------------------------------------------------------- sbt in the image
def sbt_arg(a: str) -> str:
    """One runMain argument as sbt's parser takes it: quoted when it holds a space."""
    return f'"{a}"' if " " in a else a


def run_script(src: Path, pts: list[tuple[dict, dict, Path]], mem: int) -> str:
    cmds = ["compile"]
    for _p, cfg, d in pts:
        args = [{"{sv}": str(d / "sv"), "{hdr}": str(d / "hdr")}.get(a, a) for a in cfg["args"]]
        cmds.append(" ".join(["runMain", cfg["main"], *map(sbt_arg, args)]))
    return ("set -e\n"
            f"cd {shlex.quote(str(src / 'hw' / 'chisel'))}\n"
            f"sbt -batch -mem {mem} " + " ".join(shlex.quote(c) for c in cmds) + "\n")


def podman_cmd(image: str, script: Path, mount: Path = ROOT) -> list[str]:
    """`podman run --rm` of `bash script` in the image, `mount` mounted at its own path (default this repo;
    cluster/cluster.py mounts the parent of the sibling repos) and the home folder's Scala caches at /root (SC6)."""
    home = Path.home()
    cmd = ["podman", "run", "--rm", "-v", f"{mount}:{mount}"]
    for c in CACHES:
        (home / c).mkdir(parents=True, exist_ok=True)
        cmd += ["-v", f"{home / c}:/root/{c}"]
    return cmd + [image, "bash", str(script)]


SUCCESS = re.compile(r"^\[(success|error)\] Total time: (\d+) s", re.M)
RUNNING = re.compile(r"^\[info\] running (\S+)", re.M)


def sections(log: str, n: int) -> tuple[list[str], list[tuple[str, int]]]:
    """The log split at each '[info] running' line (n runMain calls), and every command's (status, seconds)."""
    starts = [m.start() for m in RUNNING.finditer(log)]
    parts = [log[a:b] for a, b in zip(starts, starts[1:] + [len(log)])]
    parts += [""] * (n - len(parts))
    return parts[:n], [(m.group(1), int(m.group(2))) for m in SUCCESS.finditer(log)]


# ---------------------------------------------------------------- xbar_mix (CSYN1 R3c): no sbt
def make_mix(grid: dict, p: dict, cfg: dict) -> str:
    """rtl/xbar_mix/<point>.zip from its base xbar zip and strm/xbar_mix.py's wrapper; a line for the report."""
    b = base_of(grid, p)
    bz = zip_of(b)
    if not up_to_date(b, config(grid, b)):
        raise RuntimeError(f"base {bz.relative_to(ROOT)} missing or stale")
    sv = arc.read(bz, "SparseInterconnect.sv")
    text = sv.decode()
    ro, wo = p["params"]["ro"], p["params"]["wo"]
    wrap = xbar_mix.wrapper(text, ro, wo)
    si_ports = len(xbar_mix.ports(text))
    mix_ports = len(xbar_mix.ports(wrap, "xbar_mix"))
    bpj = json.loads(arc.read_text(bz, "point.json"))
    keep = ("sbt", "chisel", "scala", "firtool", "snax_cluster_commit", "chisel_float_commit", "image")
    pj = {"point": p["point"], "set": MIX, "top": "xbar_mix", "base": cfg["base"],
          "modules": bpj.get("modules", []) + ["xbar_mix"], **{k: bpj.get(k, "") for k in keep},
          "base_date": bpj.get("date", ""), "sparse_interconnect_md5": hashlib.md5(sv).hexdigest(),
          "sparse_interconnect_ports": si_ports, "xbar_mix_ports": mix_ports, "ro": ro, "wo": wo,
          "date": dt.datetime.now().isoformat(timespec="seconds")}
    arc.write(zip_of(p), {
        "SparseInterconnect.sv": sv, "xbar_mix.sv": wrap.encode(),
        "filelist.f": b"# top: xbar_mix\nSparseInterconnect.sv\nxbar_mix.sv\n",
        "config.json": config_text(cfg).encode(), "point.json": (json.dumps(pj, indent=1) + "\n").encode()})
    return f"ports {mix_ports} of SparseInterconnect's {si_ports}"


# ---------------------------------------------------------------- main
def run_sbt(grid: dict, work: list[tuple[dict, dict, Path]], args) -> tuple[list[str], list[str]]:
    """The sbt points: one sbt call in the image, a zip per point made; (made, failed)."""
    sc, sub_sha = check_checkout(grid)
    if TMP.exists():
        sys.exit(f"{TMP.relative_to(ROOT)} exists: another strm-rtl running, or a crash left it (remove it)")
    made, failed = [], []
    try:
        src = TMP / "src"
        export_sources(grid, sc, sub_sha, src)
        ver = versions(src)
        for p, cfg, d in work:
            d.mkdir(parents=True)
            (d / "config.json").write_text(config_text(cfg))
        script = TMP / "run.sh"
        script.write_text(run_script(src, work, args.mem))
        cmd = podman_cmd(grid["image"], script)
        limit = args.timeout or 600 + 120 * len(work)
        print(f"snax_cluster {sc} at {grid['snax_cluster']['commit']} (chisel-float {sub_sha[:12]}), "
              f"sbt {ver['sbt']}, Chisel {ver['chisel']}; image {grid['image']}; {len(work)} point(s), "
              f"timeout {limit} s", flush=True)
        t_call = time.monotonic()
        try:
            done = subprocess.run(cmd, capture_output=True, text=True, timeout=limit, check=False)
            log, rc = done.stdout + done.stderr, done.returncode
        except subprocess.TimeoutExpired as e:
            log = (e.stdout or b"").decode(errors="replace") + (e.stderr or b"").decode(errors="replace")
            log += f"\n[strm-rtl] timeout after {limit} s\n"
            rc = -1
        wall = time.monotonic() - t_call
        parts, times = sections(log, len(work))
        cmd_s = sum(s for _st, s in times)
        compile_s = times[0][1] if times else None
        print(f"sbt call: {wall:.1f} s wall, exit {rc}; compile {compile_s} s; "
              f"start-up and exit (wall minus the commands' total times) {wall - cmd_s:.1f} s", flush=True)
        for i, (p, cfg, d) in enumerate(work):
            name = f"{p['set']}/{p['point']}"
            st = times[i + 1] if i + 1 < len(times) else None
            try:
                if st is None or st[0] != "success":
                    raise RuntimeError("runMain failed" if st else "runMain not run (sbt stopped before it)")
                members, facts = bundle(cfg, d / "sv")
            except Exception as e:      # noqa: BLE001 - a failure is a row, not a crash
                tail = (parts[i] or log).rstrip().splitlines()[-TAIL:]
                failed.append(name)
                print(f"fail  {name}: {e}\n  " + "\n  ".join(tail), flush=True)
                continue
            pj = {"point": p["point"], "set": p["set"], **facts, **ver,
                  "snax_cluster_commit": grid["snax_cluster"]["commit"], "chisel_float_commit": sub_sha,
                  "image": grid["image"], "runmain_s": st[1], "date": dt.datetime.now().isoformat(timespec="seconds")}
            members.update({"config.json": config_text(cfg).encode(), "point.json": (json.dumps(pj, indent=1) + "\n").encode(),
                            "gen.log": parts[i].encode()})
            arc.write(zip_of(p), members)      # test-read before it replaces anything (X51)
            made.append(name)
            print(f"made  {name}  {facts['top']}  {len(facts['modules'])} modules  runMain {st[1]} s  "
                  f"-> {zip_of(p).relative_to(ROOT)}", flush=True)
        if rc and not failed and len(made) == len(work):
            print(f"note: sbt exit {rc} with every point made", flush=True)
    finally:
        shutil.rmtree(TMP, ignore_errors=True)
    return made, failed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="+", default=[], metavar="POINT", help="point names or globs")
    ap.add_argument("--set", choices=SETS, action="append", default=[], help="one set only (repeatable)")
    ap.add_argument("--list", action="store_true", help="list the selected points and whether each is made")
    ap.add_argument("--dry-run", action="store_true", help="print the configs and the sbt script, run nothing")
    ap.add_argument("--mem", type=int, default=4096, help="sbt -mem in MB (default 4096)")
    ap.add_argument("--timeout", type=int, default=0, help="seconds for the sbt call (default 600 + 120 per point)")
    args = ap.parse_args()
    grid = load_grid()
    pts = select(all_points(grid), args.only, args.set)
    if not pts:
        sys.exit("no point matches (--list shows them)")
    todo = [(p, config(grid, p)) for p in pts]
    if args.list:
        for p, cfg in todo:
            print(f"{p['set']}/{p['point']}  {'made' if up_to_date(p, cfg) else 'to make'}  {cfg['top']}  "
                  f"{json.dumps(p['params'])}")
        return 0
    skip = [p for p, cfg in todo if up_to_date(p, cfg)]
    todo = [(p, cfg) for p, cfg in todo if not up_to_date(p, cfg)]
    for p in skip:
        print(f"skip  {p['set']}/{p['point']}: {zip_of(p).relative_to(ROOT)} has the same config", flush=True)
    mix = [(p, cfg) for p, cfg in todo if p["set"] == MIX]
    todo = [(p, cfg) for p, cfg in todo if p["set"] != MIX]
    names = {f"{p['set']}/{p['point']}" for p, _cfg in todo}
    for p, _cfg in mix:      # a missing or stale base is made by sbt first, in the same call
        b = base_of(grid, p)
        bcfg = config(grid, b)
        if f"xbar/{b['point']}" not in names and not up_to_date(b, bcfg):
            print(f"base  xbar/{b['point']}: to make for {MIX}/{p['point']}", flush=True)
            todo.append((b, bcfg))
            names.add(f"xbar/{b['point']}")
    if not todo and not mix:
        print(f"\nnothing to make ({len(skip)} up to date)")
        return 0
    work = [(p, cfg, TMP / p["set"] / p["point"]) for p, cfg in todo]
    if args.dry_run:
        for _p, cfg, _d in work:
            print(config_text(cfg), end="")
        if work:
            print(run_script(TMP / "src", work, args.mem), end="")
            print(" ".join(podman_cmd(grid["image"], TMP / "run.sh")))
        for p, cfg in mix:
            print(config_text(cfg), end="")
            print(f"# {MIX}/{p['point']}: {zip_of(base_of(grid, p)).relative_to(ROOT)}'s SparseInterconnect.sv in "
                  f"xbar_mix.wrapper(ro {cfg['ro']}, wo {cfg['wo']}) -> {zip_of(p).relative_to(ROOT)}")
        return 0
    t0 = time.monotonic()
    made, failed = run_sbt(grid, work, args) if work else ([], [])
    for p, cfg in mix:
        name = f"{MIX}/{p['point']}"
        try:
            what = make_mix(grid, p, cfg)
        except Exception as e:      # noqa: BLE001 - a failure is a row, not a crash
            failed.append(name)
            print(f"fail  {name}: {e}", flush=True)
            continue
        made.append(name)
        print(f"made  {name}  xbar_mix  {what}  -> {zip_of(p).relative_to(ROOT)}", flush=True)
    print(f"\n{len(made)} made, {len(failed)} failed, {len(skip)} skipped, in {time.monotonic() - t0:.0f} s")
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
