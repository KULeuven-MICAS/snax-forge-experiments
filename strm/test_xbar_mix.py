"""strm/xbar_mix.py on a stub SparseInterconnect with the emitted port names and widths (no sbt, no DC).

    pixi run python strm/test_xbar_mix.py

The stub has SparseInterconnect's ports as firtool writes them (grouped continuation lines included) for N inputs
and B banks at strm/grid.json's fixed widths; its body only makes every output depend on the inputs. With Verilator
on PATH the wrapper is also linted against the stub (every pin connected, widths matching); without it that part is
skipped and says so.
"""

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import xbar_mix  # noqa: E402

REQ = [("addr", 16), ("write", -1), ("amo", 3), ("data", 63), ("strb", 7), ("priority", -1), ("user", 2)]
MEM = [("addr", 7), ("write", -1), ("amo", 3), ("data", 63), ("strb", 7), ("priority", -1), ("user", 2)]


def w(msb: int) -> str:
    return "      " if msb < 0 else f"[{msb}:0]".ljust(6)


def stub(n: int, b: int) -> str:
    """A SparseInterconnect with firtool's port style: clock and reset grouped, then the vectors' fields."""
    lines = ["  input         clock,", "                reset,"]
    for i in range(n):
        lines += [f"  output        io_tcdmReqs_{i}_ready,", f"  input         io_tcdmReqs_{i}_valid,"]
        lines += [f"  input  {w(m)} io_tcdmReqs_{i}_bits_{f}," for f, m in REQ]
    for i in range(n):
        lines += [f"  input         io_tcdmRsps_{i}_ready,", f"  output        io_tcdmRsps_{i}_valid,",
                  f"  output [63:0] io_tcdmRsps_{i}_bits_data,"]
    for o in range(b):
        lines += [f"  input         io_memReqs_{o}_ready,", f"  output        io_memReqs_{o}_valid,"]
        lines += [f"  output {w(m)} io_memReqs_{o}_bits_{f}," for f, m in MEM]
    for o in range(b):
        lines += [f"  output        io_memRsps_{o}_ready,", f"  input         io_memRsps_{o}_valid,",
                  f"  input  [63:0] io_memRsps_{o}_bits_data" + ("," if o < b - 1 else "")]
    body = []
    x = " ^ ".join(f"io_tcdmReqs_{i}_bits_data ^ {{60'b0, io_tcdmReqs_{i}_bits_amo}} ^ "
                   f"{{63'b0, io_tcdmReqs_{i}_bits_write}}" for i in range(n))
    for i in range(n):
        body += [f"  assign io_tcdmReqs_{i}_ready = io_memReqs_0_ready;",
                 f"  assign io_tcdmRsps_{i}_valid = io_memRsps_0_valid & io_tcdmRsps_{i}_ready;",
                 f"  assign io_tcdmRsps_{i}_bits_data = io_memRsps_{i % b}_bits_data;"]
    for o in range(b):
        body += [f"  assign io_memReqs_{o}_valid = io_tcdmReqs_{o % n}_valid;",
                 f"  assign io_memReqs_{o}_bits_addr = io_tcdmReqs_{o % n}_bits_addr[7:0];",
                 f"  assign io_memReqs_{o}_bits_write = io_tcdmReqs_{o % n}_bits_write;",
                 f"  assign io_memReqs_{o}_bits_amo = io_tcdmReqs_{o % n}_bits_amo;",
                 f"  assign io_memReqs_{o}_bits_data = {x};",
                 f"  assign io_memReqs_{o}_bits_strb = io_tcdmReqs_{o % n}_bits_strb;",
                 f"  assign io_memReqs_{o}_bits_priority = io_tcdmReqs_{o % n}_bits_priority;",
                 f"  assign io_memReqs_{o}_bits_user = io_tcdmReqs_{o % n}_bits_user;",
                 f"  assign io_memRsps_{o}_ready = 1'b1;"]
    return ("// Generated by CIRCT firtool-1.62.0 (stub)\nmodule SparseInterconnect(\n" + "\n".join(lines)
            + "\n);\n" + "\n".join(body) + "\nendmodule\n")


def names(text: str) -> set[str]:
    return {n for _d, _m, n in xbar_mix.ports(text, "xbar_mix")}


def test_ports():
    ps = xbar_mix.ports(stub(6, 4))
    assert ps[0] == ("input", -1, "clock") and ps[1] == ("input", -1, "reset")
    assert ("input", 16, "io_tcdmReqs_0_bits_addr") in ps and ("output", 63, "io_tcdmRsps_5_bits_data") in ps
    assert xbar_mix.n_inputs(ps) == 6


def test_ties():
    t = xbar_mix.wrapper(stub(6, 4), ro=3, wo=1)
    kept = names(t)
    for i in range(3):        # read-only
        assert {f"io_tcdmReqs_{i}_bits_{f}" for f in ("write", "data", "amo")}.isdisjoint(kept)
        assert f"io_tcdmReqs_{i}_bits_strb" in kept and f"io_tcdmRsps_{i}_bits_data" in kept
        assert f".io_tcdmReqs_{i}_bits_data('0)" in t
    assert {"io_tcdmReqs_3_bits_write", "io_tcdmReqs_3_bits_amo", "io_tcdmRsps_3_bits_data"}.isdisjoint(kept)
    assert "io_tcdmReqs_3_bits_data" in kept and ".io_tcdmReqs_3_bits_write(1'b1)" in t
    assert ".io_tcdmRsps_3_bits_data()" in t
    for i in (4, 5):          # read-write
        assert {f"io_tcdmReqs_{i}_bits_{f}" for f in ("write", "data", "amo")} <= kept
    assert all(f".io_tcdmRsps_{i}_ready(1'b1)" in t for i in range(6))
    assert all(f".io_memRsps_{o}_valid(1'b1)" in t and f".io_memRsps_{o}_ready()" in t
               and f".io_memReqs_{o}_bits_priority()" in t for o in range(4))
    assert "io_memRsps_0_valid" not in kept and "io_memReqs_0_bits_priority" not in kept


def test_rw_and_limits():
    t = xbar_mix.wrapper(stub(4, 4), ro=0, wo=0)
    assert "no read-only input, no write-only input, 0..3 read-write" in t
    for bad in ((5, 0), (2, 3), (-1, 0)):
        try:
            xbar_mix.wrapper(stub(4, 4), *bad)
        except ValueError:
            continue
        raise AssertionError(f"{bad} accepted")


def test_lint():
    v = shutil.which("verilator")
    if not v:
        print("skip test_lint: no verilator on PATH")
        return
    with tempfile.TemporaryDirectory() as d:
        for ro, wo in ((0, 0), (3, 1), (6, 0), (0, 6)):
            (Path(d) / "si.sv").write_text(stub(6, 4))
            (Path(d) / "mix.sv").write_text(xbar_mix.wrapper(stub(6, 4), ro, wo))
            r = subprocess.run([v, "--lint-only", "-Wall", "-Wno-UNUSEDSIGNAL", "-Wno-DECLFILENAME", "-Wno-PINCONNECTEMPTY",
                                "--top-module", "xbar_mix", "si.sv", "mix.sv"], cwd=d, capture_output=True, text=True)
            assert r.returncode == 0, f"ro {ro} wo {wo}:\n{r.stderr[:2000]}"


