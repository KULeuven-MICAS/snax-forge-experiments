#!/usr/bin/env python3
"""sim/report_energy.py - results/hls/report_energy.md from results/hls/<tech>/power_pt.csv.

  pixi run python sim/report_energy.py

The energy of whole tasks: every point at every size in its hls-exercises rtl/<point>/sizes.txt
(`pwr run ... --size all`), rand64, seed 0. One section per technology; per kernel and size a table
with one row per case and W.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

SIM = Path(__file__).resolve().parent
sys.path.insert(0, str(SIM))
from sources import hls  # noqa: E402

ROOT = SIM.parent
RESULTS = ROOT / "results" / "hls"
TECHS = ["nangate45", "nangate15"]
CASES = ["unopt", "opt", "dace"]
OUT = RESULTS / "report_energy.md"

HEADER = """# Energy of whole tasks

Generated by snax-forge-experiments' `sim/report_energy.py` from `results/hls/<tech>/power_pt.csv`. Do not edit; rerun `pixi run python sim/report_energy.py`.

How the numbers were made (`docs/power.md`): every HLS point of tiers done and untiered at every size in its hls-exercises `rtl/<point>/sizes.txt` (the workloads of snax-forge's recipes), `pwr run ... --size all`. Stimulus rand64: uniform full-range int64, numpy `default_rng(0)`. A functional, zero-delay Questa simulation of the mapped netlist DC wrote at a 10 ns clock, every output checked against `sim/ref.py` and the cycles equal to cosim's; the busy window (start to done) through vcd2saif into PrimePower on the same netlist. Dynamic energy only (docs X13): no leakage.

- **cycles**: rising edges from the first edge sampling `ap_start` = 1 to the first sampling `ap_done` = 1 (docs X12); equal to cosim's latency at this size.
- **e_run_nj**: the task's dynamic energy, e_dyn per cycle x cycles, in nJ.
- **pJ/elem**: e_run divided by the elements the size names (n, or m x n).
- **comb %**: e_comb's share of e_dyn (the rest is flop energy: clock, register, sequential groups).
- **best**: the lowest-energy row (`E`) and the fewest-cycle row or rows (`C`) of the table.

`dace_w1` of dot, axpy and rowsum is parked: it needs a RAM macro neither library has.
"""


def load(tech: str) -> list[dict]:
    f = RESULTS / tech / "power_pt.csv"
    if not f.is_file():
        return []
    with f.open(newline="") as fh:
        return [r for r in csv.DictReader(fh) if r["status"] == "ok" and r["seed"] == "0"]


def main() -> int:
    out = [HEADER]
    for tech in TECHS:
        rows = load(tech)
        if not rows:
            continue
        out.append(f"\n## {tech}\n")
        kernels = sorted({r["point"].rsplit("/", 1)[0] for r in rows})
        for tk in kernels:
            prm = hls.params_of(tk + "/x_w1")
            tags = [hls.size_tag(s) for s in prm["sizes"]]
            out.append(f"\n### {tk.split('/')[1]} ({tk.split('/')[0]})")
            for tag in tags:
                sel = []
                for r in rows:
                    pt = r["point"]
                    if not pt.startswith(tk + "/") or r["size"] != tag or tag not in hls.sizes_txt(pt):
                        continue
                    case, w = hls.case_w(pt)
                    sel.append((CASES.index(case), w, case, r))
                if not sel:
                    continue
                sel.sort(key=lambda x: (x[0], x[1]))
                e = {id(r): float(r["e_run_pj"]) for *_, r in sel}
                emin = min(e.values())
                cmin = min(int(r["cycles"]) for *_, r in sel)
                out.append(f"\n**{tag}**: {int(sel[0][3]['beats']) * sel[0][1]} elements\n")
                out.append("| case | W | cycles | e_run_nj | pJ/elem | comb % | best |")
                out.append("|---|---|---|---|---|---|---|")
                for _, w, case, r in sel:
                    elems = int(r["beats"]) * w
                    best = " ".join(m for m, ok in (("E", e[id(r)] == emin), ("C", int(r["cycles"]) == cmin)) if ok)
                    out.append(f"| {case} | {w} | {r['cycles']} | {e[id(r)] / 1000:.4g} | {e[id(r)] / elems:.4g} | "
                               f"{100 * float(r['e_comb_pj']) / float(r['e_dyn_pj']):.1f} | {best} |")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
